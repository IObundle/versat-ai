void *Software_AveragePool(void *inputX, void *output, int index,
                           AveragePoolInfo *info) {
  float *view = (float *)inputX;
  float *out = (float *)output;

  int64_t *inputDims = VERSAT_AveragePoolInfo_inputDims(info);
  int64_t *outputDims = VERSAT_AveragePoolInfo_outputDims(info);
  int *kernelDims = VERSAT_AveragePoolInfo_kernelDims(info);
  int *strideDims = VERSAT_AveragePoolInfo_strideDims(info);
  int *padsDims = VERSAT_AveragePoolInfo_padsDims(info);

  ExtraInfo extra = CalculateExtraInfo_AveragePool(info);

  AddressGen outGenInst = StartAddress(outputDims, outputDims, info->dims);
  AddressGen *outGen = &outGenInst;

  // We probably want to move this to the array generated by python.
  // Emit the proper array directly
  int stride[MAX_DIMS];
  stride[0] = 1;
  stride[1] = 1;
  for (int i = 0; i < info->strideSize; i++) {
    stride[i + 2] = strideDims[i];
  }

  int offset[MAX_DIMS];
  offset[0] = 0;
  offset[1] = 0;
  offset[2] = extra.leftPadH;
  offset[3] = extra.leftPadW;

  for (; Address_IsValid(outGen); Address_Advance(outGen)) {
    float sum = 0.0f;
    float div = 0.0f;

    AddressGen inputPos = Address_Map2(outGen, inputDims, stride, offset);
    KernelGen kernInst = StartKernel(&inputPos, kernelDims, 2);
    KernelGen *kern = &kernInst;
    for (; Kernel_IsValid(kern); Kernel_Advance(kern)) {
      if (Kernel_IsInsidePad(kern)) {
        continue;
      }
      int index = Kernel_GetValue(kern);

      float val = view[index];

      sum += val;
      div += 1.0f;
    }

    int outputIndex = Address_GetValue(outGen);
    out[outputIndex] = (sum / div);
  }

  return output;
}

